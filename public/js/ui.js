let toastTimer;
export function toast(msg) {
  document.querySelectorAll('.toast').forEach((e) => e.remove());
  const el = document.createElement('div');
  el.className = 'toast';
  el.textContent = msg;
  document.body.appendChild(el);
  clearTimeout(toastTimer);
  toastTimer = setTimeout(() => el.remove(), 2200);
}

export function modal(innerHTML) {
  const bg = document.createElement('div');
  bg.className = 'modal-bg';
  bg.innerHTML = `<div class="modal"><div class="grip"></div>${innerHTML}</div>`;
  document.body.appendChild(bg);
  const close = () => bg.remove();
  bg.addEventListener('click', (e) => { if (e.target === bg) close(); });
  return { el: bg.querySelector('.modal'), close };
}

export function confirmDialog(message, onYes) {
  const { el, close } = modal(`
    <h3>${message}</h3>
    <div class="btn-row">
      <button class="btn ghost" data-no>${t('c.cancel')}</button>
      <button class="btn danger" data-yes>${t('c.confirm')}</button>
    </div>`);
  el.querySelector('[data-no]').onclick = close;
  el.querySelector('[data-yes]').onclick = () => { close(); onYes(); };
}

export function todayStr() {
  const d = new Date();
  const p = (x) => String(x).padStart(2, '0');
  return `${d.getFullYear()}-${p(d.getMonth() + 1)}-${p(d.getDate())}`;
}
export function curMonth() { return todayStr().slice(0, 7); }
