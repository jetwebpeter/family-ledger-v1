export const state = { user: null, settings: {}, currency: 'NT$', lang: 'zh' };

export function money(n, sign) {
  n = Number(n) || 0;
  const s = state.currency + ' ' + Math.abs(n).toLocaleString('en-US', { maximumFractionDigits: 0 });
  if (sign && n > 0) return '+' + s;
  if (sign && n < 0) return '-' + s;
  return (n < 0 ? '-' : '') + s;
}

